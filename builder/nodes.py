"""Small constructors for n8n 2.4.x node JSON (formats verified against n8n 2.4.6).

Credentials are always referenced by name only: ``{"<type>": {"name": "<name>"}}``. n8n binds the
name to a credential of that type when the workflow is imported, so no id or secret is in a file.
"""
from __future__ import annotations

import json
import uuid
from pathlib import Path

from runner import spec

JS_DIR = Path(__file__).resolve().parent / "js"
NAMESPACE = uuid.UUID("6f1c1e1e-5a8c-4d39-9a59-0c0de0f0a5e1")


def node(name: str, kind: str, version: float, position: tuple[int, int], parameters: dict,
         credentials: dict | None = None, **extra: object) -> dict:
    """One node dict with a stable id derived from its name."""
    out = {"id": str(uuid.uuid5(NAMESPACE, name)), "name": name, "type": f"n8n-nodes-base.{kind}",
           "typeVersion": version, "position": list(position), "parameters": parameters}
    if credentials:
        out["credentials"] = {ctype: {"name": cname} for ctype, cname in credentials.items()}
    out.update(extra)
    return out


def spec_constants() -> dict:
    """Every UPPER_CASE constant of ``runner.spec`` as JSON-ready data (tuples become lists)."""
    return json.loads(json.dumps({k: v for k, v in vars(spec).items() if k.isupper()}))


def code_node(name: str, main_file: str, position: tuple[int, int]) -> dict:
    """A Code node whose JS is ``const SPEC = ...`` + helpers.js + the given main file."""
    js = "\n".join([
        "// Generated by builder/build_workflows.py from runner/spec.py - edit those, not this node.",
        "const SPEC = " + json.dumps(spec_constants()) + ";",
        (JS_DIR / "helpers.js").read_text(),
        (JS_DIR / main_file).read_text(),
    ])
    return node(name, "code", 2, position, {"jsCode": js})


def webhook(name: str, path: str, position: tuple[int, int]) -> dict:
    """A POST webhook guarded by a header token (credential ``Ops Webhook Token``)."""
    params = {"httpMethod": "POST", "path": path, "authentication": "headerAuth", "options": {}}
    return node(name, "webhook", 2, position, params, {"httpHeaderAuth": "Ops Webhook Token"},
                webhookId=str(uuid.uuid5(NAMESPACE, "webhook:" + path)))


def ops_config(values: dict[str, str], position: tuple[int, int]) -> dict:
    """A Set node holding the per-install settings (placeholders, edit after import)."""
    rows = [{"id": str(uuid.uuid5(NAMESPACE, key)), "name": key, "value": value, "type": "string"}
            for key, value in values.items()]
    params = {"assignments": {"assignments": rows}, "includeOtherFields": True, "options": {}}
    return node("Ops config", "set", 3.4, position, params)


def claude_call(name: str, position: tuple[int, int]) -> dict:
    """HTTP Request to the Messages API; the body is built by the previous Code node."""
    headers = [{"name": "anthropic-version", "value": spec.ANTHROPIC_VERSION},
               {"name": "content-type", "value": "application/json"}]
    params = {
        "method": "POST", "url": "https://api.anthropic.com/v1/messages",
        "authentication": "genericCredentialType", "genericAuthType": "httpHeaderAuth",
        "sendHeaders": True, "headerParameters": {"parameters": headers},
        "sendBody": True, "specifyBody": "json", "jsonBody": "={{ JSON.stringify($json.claude_request) }}",
        "options": {"timeout": 120000, "response": {"response": {"neverError": True}}},
    }
    return node(name, "httpRequest", 4.2, position, params, {"httpHeaderAuth": "Anthropic API"},
                onError="continueRegularOutput")


def switch(name: str, field: str, outputs: list[str], position: tuple[int, int]) -> dict:
    """Switch v3 on a string field: one named output per value plus an extra fallback output."""
    rules = [{
        "conditions": {
            "options": {"caseSensitive": True, "leftValue": "", "typeValidation": "strict"},
            "conditions": [{"leftValue": "={{ " + field + " }}", "rightValue": value,
                            "operator": {"type": "string", "operation": "equals"}}],
            "combinator": "and",
        },
        "renameOutput": True, "outputKey": value,
    } for value in outputs]
    return node(name, "switch", 3, position, {"rules": {"values": rules}, "options": {"fallbackOutput": "extra"}})


def postgres_query(name: str, query: str, row_expr: str, position: tuple[int, int]) -> dict:
    """Postgres executeQuery with the whole row passed as one JSON parameter ($1)."""
    params = {"operation": "executeQuery", "query": query,
              "options": {"queryReplacement": "={{ JSON.stringify(" + row_expr + ") }}"}}
    return node(name, "postgres", 2.5, position, params, {"postgres": "Ops Postgres"})
